private int getJumlahPertemuan() {
    return cbSks.getSelectedItem().toString().trim().equals("3") ? 21 : 14;
}

private String getGrade(double absensiPersen, double nilaiAkhir) {
    if (absensiPersen < 50) return "E";
    if (absensiPersen < 75) return "D";
    if (nilaiAkhir > 80) return "A";
    if (nilaiAkhir > 60) return "B";
    if (nilaiAkhir > 40) return "C";
    return "D";
}

private boolean validasi() {
    if (nimTxt.getText().trim().isEmpty() || namaTxt.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "NIM dan Nama wajib diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
        return false;
    }
    if (!rbLaki.isSelected() && !rbWanita.isSelected()) {
        JOptionPane.showMessageDialog(this, "Pilih jenis kelamin!", "Peringatan", JOptionPane.WARNING_MESSAGE);
        return false;
    }
    try {
        int presensi = Integer.parseInt(presisiTxt.getText().trim());
        double tugas = Double.parseDouble(tugasTxt.getText().trim());
        double uts = Double.parseDouble(utsTxt.getText().trim());
        double uas = Double.parseDouble(uasTxt.getText().trim());

        if (presensi < 0 || presensi > getJumlahPertemuan()) {
            JOptionPane.showMessageDialog(this, "Presensi harus 0 - " + getJumlahPertemuan(), "Peringatan", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        if (tugas < 0 || tugas > 100 || uts < 0 || uts > 100 || uas < 0 || uas > 100) {
            JOptionPane.showMessageDialog(this, "Nilai Tugas, UTS, UAS harus 0 - 100", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return false;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Presensi dan nilai harus berupa angka!", "Error", JOptionPane.ERROR_MESSAGE);
        return false;
    }
    return true;
}

private void keluar() {
    int pilih = JOptionPane.showConfirmDialog(this, "Yakin ingin keluar?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
    if (pilih == JOptionPane.YES_OPTION) System.exit(0);
}
