    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
        // TODO add your handling code here:
        if (!validasi()) return;

        int pertemuan = getJumlahPertemuan();
        int presensi = Integer.parseInt(presisiTxt.getText().trim());
        double tugas = Double.parseDouble(tugasTxt.getText().trim());
        double nilaiUts = Double.parseDouble(utsTxt.getText().trim());
        double nilaiUas = Double.parseDouble(uasTxt.getText().trim());

        double absensiPersen = ((double) presensi / pertemuan) * 100;
        double nAbsensi = absensiPersen * 0.1;
        double nTugas = tugas * 0.2;
        double nUTS = nilaiUts * 0.3;
        double nUAS = nilaiUas * 0.4;
        double nilaiAkhir = nAbsensi + nTugas + nUTS + nUAS;
        String grade = getGrade(absensiPersen, nilaiAkhir);
        gradaeTxt.setText(grade);
        finalTxt.setText(String.format("%.2f", nilaiAkhir)); 

        String jk = rbLaki.isSelected() ? "Pria" : "Wanita";
        hasilTerakhir = "NIM: " + nimTxt.getText() + "\n"
                + "Nama: " + namaTxt.getText() + "\n"
                + "Jenis Kelamin: " + jk + "\n"
                + "Mata Kuliah: " + cbMatkul.getSelectedItem() + " (" + cbSks.getSelectedItem() + " SKS)\n"
                + "Jml Pertemuan: " + pertemuan + "\n"
                + String.format("Absensi: %.2f%% (nilai %.2f)\n", absensiPersen, nAbsensi)
                + String.format("Tugas: %.2f | UTS: %.2f | UAS: %.2f\n", nTugas, nUTS, nUAS)
                + String.format("Nilai Akhir: %.2f\n", nilaiAkhir)
                + "Grade: " + grade + "\n"
                + "------------------------------\n";

        JOptionPane.showMessageDialog(this, hasilTerakhir, "Hasil Penilaian", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnProsesActionPerformed

