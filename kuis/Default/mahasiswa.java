package kuis.Default;

public class mahasiswa {
    private String name;
    private long nim;
    private int ipk;

    public void setName(String name) {
        this.name = name;
    }

    public String getName() {
        return name;
    }

    public void setNim(long nim) {
        this.nim = nim;
    }

    public long getNim() {
        return nim;
    }

    public void setIpk(int ipk) {
        this.ipk = ipk;
    }

    public int getIpk() {
        return ipk;
    }
}
